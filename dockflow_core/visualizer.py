"""3D visualization through the open-source PyMOL API.

Two rendering paths:

* **PyMOL** (preferred): a ``.pml`` script is generated (pure string
  building, fully testable), then executed either

  - in a subprocess: ``pymol -cq script.pml`` (most robust), or
  - in-process: ``pymol.finish_launching(['pymol', '-cq'])`` + ``cmd.do``.

  Products: ray-traced PNG, a ``.pse`` session, a CGO wire-frame grid box
  and per-pose colouring by rank/affinity.

* **matplotlib fallback** for machines without PyMOL (CI, minimal installs):
  a static 3D scatter of receptor + poses + box rendered through
  ``mpl_toolkits.mplot3d``.

The generated ``.pse`` sessions can be opened interactively with
:func:`open_session` (launches the PyMOL GUI).
"""

from __future__ import annotations

import subprocess
from collections.abc import Sequence
from pathlib import Path

from .gridbox import GridBox
from .pdbio import parse_pdb, split_pdbqt_models
from .utils import DockFlowError, get_logger, which

logger = get_logger("visualizer")

