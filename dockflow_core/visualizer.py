def render_complex(
    receptor_path: str | Path,
    ligand_pose_paths: Sequence[str | Path],
    box: GridBox | None,
    out_png: str | Path,
    session_path: str | Path | None = None,
    affinities: Sequence[float | None] | None = None,
    engine: str = "auto",
    pymol_executable: str | None = None,
    timeout: float = 600.0,
) -> Path:
    """Render receptor + poses + box to ``out_png``.

    Uses PyMOL when available (subprocess preferred, in-process fallback),
    otherwise the matplotlib fallback renderer.
    """
    out_png = Path(out_png)
    out_png.parent.mkdir(parents=True, exist_ok=True)
    runner = PyMOLRunner(pymol_executable)
    use_pymol = (engine == "pymol") or (engine == "auto" and runner.available)
    if use_pymol and runner.available:
        script = build_pml_script(
            receptor_path, ligand_pose_paths, box, out_png, session_path,
            affinities=affinities,
        )
        script_path = out_png.with_suffix(".pml")
        script_path.write_text(script, encoding="utf-8")
        try:
            runner.run_script(script_path, timeout=timeout)
            if out_png.is_file():
                return out_png
            logger.warning("PyMOL finished but no PNG produced; trying in-process")
        except VisualizationError as exc:
            logger.warning("PyMOL subprocess failed (%s); trying in-process", exc)
        try:
            runner.run_script_inprocess(script)
        except VisualizationError:
            if engine == "pymol":
                raise
        if out_png.is_file():
            return out_png
        if engine == "pymol":
            raise VisualizationError("PyMOL produced no output PNG")
    return render_matplotlib(
        receptor_path, ligand_pose_paths, box, out_png, affinities=affinities
    )


def render_matplotlib(
    receptor_path: str | Path,
    ligand_pose_paths: Sequence[str | Path],
    box: GridBox | None,
    out_png: str | Path,
    affinities: Sequence[float | None] | None = None,
    receptor_stride: int = 4,
) -> Path:
    """Static fallback renderer (no PyMOL dependency)."""
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError as exc:
        raise VisualizationError(
            "neither PyMOL nor matplotlib is available for rendering"
        ) from exc
    from mpl_toolkits.mplot3d import Axes3D  # noqa: F401

    receptor_atoms = [a for a in parse_pdb(receptor_path) if not a.is_hydrogen]
    step = max(1, receptor_stride)
    receptor_atoms = receptor_atoms[::step]
    fig = plt.figure(figsize=(12, 9), constrained_layout=True)
    ax = fig.add_subplot(111, projection="3d")
    if receptor_atoms:
        xs = [a.x for a in receptor_atoms]
        ys = [a.y for a in receptor_atoms]
        zs = [a.z for a in receptor_atoms]
        ax.scatter(xs, ys, zs, s=4, c="#9aa0a6", alpha=0.35, depthshade=True,
                   label="receptor")
    for index, pose_path in enumerate(ligand_pose_paths):
        from .pdbio import parse_pdbqt

        atoms = parse_pdbqt(pose_path).atoms
        if not atoms:
            continue
        color = _POSE_COLORS[index % len(_POSE_COLORS)]
        rgb = tuple(float(v) for v in color.split(","))
        xs = [a.x for a in atoms]
        ys = [a.y for a in atoms]
        zs = [a.z for a in atoms]
        label = f"pose {index + 1}"
        if affinities is not None and index < len(affinities) \
                and affinities[index] is not None:
            label += f" ({affinities[index]:.2f})"
        ax.scatter(xs, ys, zs, s=28, c=[rgb], edgecolors="k", linewidths=0.3,
                   depthshade=True, label=label)
    if box is not None:
        corners = box.corner_points()
        edges = [
            (0, 1), (1, 2), (2, 3), (3, 0),
            (4, 5), (5, 6), (6, 7), (7, 4),
            (0, 4), (1, 5), (2, 6), (3, 7),
        ]
        for a, b in edges:
            ax.plot(
                [corners[a][0], corners[b][0]],
                [corners[a][1], corners[b][1]],
                [corners[a][2], corners[b][2]],
                color="#1a56db", linewidth=1.0, linestyle="--",
            )
        ax.scatter([], [], [], c="#1a56db", marker="s", label="grid box")
    ax.set_xlabel("X (A)")
    ax.set_ylabel("Y (A)")
    ax.set_zlabel("Z (A)")
    ax.set_title("DockFlow-Automator render (matplotlib fallback)")
    ax.legend(loc="upper left", bbox_to_anchor=(1.02, 1.0), fontsize=9)
    try:
        ax.set_box_aspect((1.0, 1.0, 1.0))
    except AttributeError:  # pragma: no cover - very old matplotlib
        pass
    out_png = Path(out_png)
    out_png.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_png, dpi=180)
    plt.close(fig)
    return out_png


def open_session(session_path: str | Path, pymol_executable: str | None = None) -> None:
    """Open a .pse session in the interactive PyMOL GUI."""
    executable = which(pymol_executable or "pymol")
    if executable is None:
        raise VisualizationError(
            "PyMOL executable not found; install pymol-open-source to open sessions"
        )
    subprocess.Popen([executable, str(session_path)])  # noqa: S603


def render_best_poses(
    receptor_path: str | Path,
    poses_pdbqt: str | Path,
    box: GridBox | None,
    out_dir: str | Path,
    ligand_name: str,
    affinities: Sequence[float | None] | None = None,
    engine: str = "auto",
    session: bool = True,
    top: int = 5,
    pymol_executable: str | None = None,
) -> list[Path]:
    """Split a multi-pose PDBQT and render the top poses.

    Returns the list of produced image paths (PyMOL or matplotlib).
    """
    out_dir = Path(out_dir)
    pose_files = split_pdbqt_models(poses_pdbqt, out_dir, ligand_name)[:top]
    images: list[Path] = []
    for index, pose_file in enumerate(pose_files):
        subset = affinities[index:index + 1] if affinities is not None else None
        out_png = out_dir / f"{ligand_name}_render_{index + 1:02d}.png"
        render_complex(
            receptor_path, [pose_file], box, out_png,
            session_path=out_dir / f"{ligand_name}_session.pse" if session else None,
            affinities=subset,
            engine=engine,
            pymol_executable=pymol_executable,
        )
        images.append(out_png)
    return images
